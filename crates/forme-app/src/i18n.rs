//! UI language (Romain, 17 nov. 2026: « fait l'app en anglais »).
//!
//! The UI is written in French. The NURBS app shows it in English: `tr`
//! translates a fixed text, `trd` a text built with `format!` by replacing
//! its French fragments (longest first). Forme stays in French.
//! `FORME_LANG=en|fr` overrides the default of each app.

use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static EN: AtomicBool = AtomicBool::new(false);

pub fn set_english(on: bool) {
    EN.store(on, Ordering::Relaxed);
    forme_core::set_english(on);
}

pub fn en() -> bool {
    EN.load(Ordering::Relaxed)
}

/// The text in the UI language (unchanged in French or when unknown).
pub fn tr(s: &str) -> &str {
    if !en() {
        return s;
    }
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| PLAIN.iter().copied().collect()).get(s).copied().unwrap_or(s)
}

/// A formatted text in the UI language: whole-text match first, then the
/// French fragments of the format strings.
pub fn trd(s: String) -> String {
    if !en() {
        return s;
    }
    let whole = tr(&s);
    if whole != s {
        return whole.to_string();
    }
    static FRAGS: OnceLock<Vec<(&'static str, &'static str)>> = OnceLock::new();
    let frags = FRAGS.get_or_init(|| {
        let mut v: Vec<_> = FRAG.to_vec();
        v.sort_by_key(|(fr, _)| std::cmp::Reverse(fr.len()));
        v
    });
    let mut out = s;
    for (fr, en) in frags {
        if out.contains(fr) {
            out = out.replace(fr, en);
        }
    }
    out
}

